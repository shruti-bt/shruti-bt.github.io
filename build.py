#!/usr/bin/env python3
"""Build the site from the Markdown files in content/ and the layouts in templates/.

Usage:  python3 build.py

Writes:
    index.html           the home page (from templates/home.html)
    gallery/index.html   the Gallery page, only when content/gallery.md has photos

Only uses the Python standard library, so there is nothing to install.
GitHub Actions runs this automatically before every deploy.
"""

import datetime
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CONTENT = ROOT / "content"
TEMPLATES = ROOT / "templates"
SITE_URL = "https://shruti-bt.github.io/"
BANNER = "<!-- GENERATED by build.py from {src}. Edit that, not this file. -->\n"

warnings = []


def warn(msg):
    warnings.append(msg)


# --------------------------------------------------------------------------
# Tiny Markdown helpers (only what this site needs: links, bold, italic)
# --------------------------------------------------------------------------

def strip_comments(text):
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def link_tag(label, url):
    external = url.startswith("http://") or url.startswith("https://")
    extra = ' target="_blank" rel="noopener"' if external else ""
    return f'<a href="{url}"{extra}>{label}</a>'


def inline(text):
    """Convert inline Markdown to HTML. The text is HTML-escaped first."""
    s = html.escape(text.strip(), quote=True)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: link_tag(m.group(1), m.group(2)), s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<![\*\w])\*(?!\s)(.+?)(?<!\s)\*(?![\*\w])", r"<em>\1</em>", s)
    return s


def plain(text):
    """Text without Markdown, e.g. for alt text."""
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    return re.sub(r"\*+", "", text).strip()


def indent(lines, n):
    pad = " " * n
    return "\n".join(pad + line if line else line for line in lines)


def fill(template, values):
    """Replace {{name}} placeholders; unknown ones are left as they are."""
    return re.sub(r"\{\{(\w+)\}\}", lambda m: values.get(m.group(1), m.group(0)), template)


def drop(page, pattern):
    """Remove a block of the page (e.g. a section with nothing to show)."""
    return re.sub(pattern, "", page, flags=re.S)


# --------------------------------------------------------------------------
# about.md: settings block + bio paragraphs
# --------------------------------------------------------------------------

def parse_about(path):
    raw = strip_comments(path.read_text(encoding="utf-8"))
    m = re.match(r"\s*---\s*\n(.*?)\n---\s*\n(.*)", raw, flags=re.S)
    if not m:
        sys.exit(f"{path.name}: missing the settings block between two --- lines at the top")
    settings_text, body = m.groups()

    settings, links, skills, highlights = {}, [], [], []
    for line in settings_text.splitlines():
        line = line.strip()
        if not line:
            continue
        key, sep, value = line.partition(":")
        if not sep:
            warn(f"{path.name}: ignored settings line (no colon): {line}")
            continue
        key, value = key.strip().lower(), value.strip()
        if key == "link":
            label, bar, url = value.partition("|")
            if not bar:
                warn(f"{path.name}: link needs 'Label | url': {line}")
                continue
            links.append((label.strip(), url.strip()))
        elif key == "highlight":
            label, _, url = value.partition("|")
            highlights.append((label.strip(), url.strip()))
        elif key == "skill":
            group, bar, items = value.partition("|")
            if not bar:
                warn(f"{path.name}: skill needs 'Group | item, item': {line}")
                continue
            skills.append((group.strip(), [i.strip() for i in items.split(",") if i.strip()]))
        else:
            settings[key] = value

    for required in ("name", "role", "photo"):
        if required not in settings:
            sys.exit(f"{path.name}: missing '{required}:' in the settings block")

    # Bio: the first paragraph is the larger intro line; "> ..." is the open-to box
    bio, lead_done = [], False
    for p in (p.strip() for p in re.split(r"\n\s*\n", body) if p.strip()):
        if p.startswith(">"):
            text = " ".join(line.lstrip(">").strip() for line in p.splitlines())
            bio.append(f'<p class="open-to">{inline(text)}</p>')
        else:
            text = " ".join(line.strip() for line in p.splitlines())
            cls = "" if lead_done else ' class="lead"'
            bio.append(f"<p{cls}>{inline(text)}</p>")
            lead_done = True

    return {
        "settings": settings,
        "links": links,
        "skills": skills,
        "highlights": highlights,
        "bio": bio,
    }


def render_links(links):
    return [f"<li>{link_tag(html.escape(label), html.escape(url))}</li>" for label, url in links]


def render_focus(focus):
    """Research areas under the role: 'focus: A | B | C' becomes 'A · B · C'."""
    areas = [a.strip() for a in focus.split("|") if a.strip()]
    if not areas:
        return []
    items = "".join(f"<li>{inline(a)}</li>" for a in areas)
    return [f'<ul class="focus-line" aria-label="Research areas">{items}</ul>']


# small outline icons for the header buttons, picked by where the button links to
ICONS = {
    "#publications": '<path d="M7 3h7l4 4v14H7z"/><path d="M14 3v4h4M10 12h5M10 16h5"/>',
    "#patents": '<path d="M9 18h6M10 21h4"/><path d="M12 3a6 6 0 0 0-3.5 10.9c.6.5 1 1.2 1 2.1h5c0-.9.4-1.6 1-2.1A6 6 0 0 0 12 3z"/>',
    "default": '<path d="M10 14a4 4 0 0 0 5.7 0l3-3a4 4 0 0 0-5.7-5.7l-1 1"/><path d="M14 10a4 4 0 0 0-5.7 0l-3 3a4 4 0 0 0 5.7 5.7l1-1"/>',
}


def render_highlights(highlights):
    """Top results under the role: 'highlight: Label | #link', shown as rust text with an icon."""
    if not highlights:
        return []
    items = []
    for label, url in highlights:
        icon = ICONS.get(url, ICONS["default"])
        svg = (f'<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" '
               f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{icon}</svg>')
        text = svg + inline(label)
        items.append(f"    <li>{link_tag(text, html.escape(url)) if url else text}</li>")
    return ['<ul class="highlights" aria-label="Research highlights">'] + items + ["</ul>"]


def render_skills(skills, service):
    """The "Skills & Service" rows at the bottom of the page."""
    def nobreak(item):  # keep each skill on one line (no breaks at spaces or hyphens)
        return html.escape(item).replace(" ", "&nbsp;").replace("-", "&#8209;")

    rows = []
    for group, items in skills:
        if items:
            rows += ["    <div>", f"        <dt>{html.escape(group)}</dt>",
                     f"        <dd>{', '.join(nobreak(i) for i in items)}</dd>", "    </div>"]
    if service:
        rows += ["    <div>", "        <dt>Service</dt>", f"        <dd>{inline(service)}</dd>", "    </div>"]
    return ['<dl class="meta-list">'] + rows + ["</dl>"] if rows else []


# --------------------------------------------------------------------------
# news.md
# --------------------------------------------------------------------------

def parse_news(path):
    raw = strip_comments(path.read_text(encoding="utf-8"))
    items = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        if not line.startswith("- ") or "|" not in line:
            warn(f"{path.name}: skipped line (expected '- Mon YYYY | text'): {line}")
            continue
        date, _, text = line[2:].partition("|")
        items += [
            '<li class="news-item">',
            f'    <span class="news-date">{html.escape(date.strip())}</span>',
            f'    <span class="news-content">{inline(text)}</span>',
            "</li>",
        ]
    return items


# --------------------------------------------------------------------------
# publications.md and patents.md (same format)
# --------------------------------------------------------------------------

def is_url(value):
    return re.match(r"(https?://|mailto:|assets/|/)", value) is not None


def parse_publications(path):
    if not path.exists():
        return []
    raw = strip_comments(path.read_text(encoding="utf-8"))
    out, used_ids = [], set()

    for n, block in enumerate(re.split(r"^##\s+", raw, flags=re.M)[1:], 1):
        title, _, rest = block.partition("\n")
        bib = None
        bm = re.search(r"```\s*bibtex\s*\n(.*?)```", rest, flags=re.S)
        if bm:
            bib = bm.group(1).strip("\n")
            rest = rest[: bm.start()] + rest[bm.end():]

        fields, buttons, tags = {}, [], []
        for line in rest.splitlines():
            line = line.strip()
            if not line:
                continue
            key, sep, value = line.partition(":")
            key, value = key.strip(), value.strip()
            if not sep:
                warn(f"{path.name}: '{title.strip()}': ignored line: {line}")
            elif key.lower() in ("authors", "venue"):
                fields[key.lower()] = value
            elif key.lower() == "tag":
                tags.append(value)
            elif is_url(value):  # any "label: url" line becomes a button
                buttons.append((key[:1].upper() + key[1:], value))
            else:
                warn(f"{path.name}: '{title.strip()}': unknown line: {line}")

        lines = ['<article class="pub">', f"    <h3>{inline(title)}</h3>"]
        if "authors" in fields:
            lines.append(f'    <div class="pub-authors">{inline(fields["authors"])}</div>')
        if "venue" in fields:
            lines.append(f'    <div class="pub-venue">{inline(fields["venue"])}</div>')

        bib_id = None
        if bib:
            km = re.match(r"\s*@\w+\s*\{\s*([^,\s]+)", bib)
            bib_id = re.sub(r"[^\w-]", "", km.group(1)) if km else f"pub{n}"
            while bib_id in used_ids:
                bib_id += "_"
            used_ids.add(bib_id)

        if buttons or bib or tags:
            lines.append('    <div class="pub-links">')
            lines += [f"        {link_tag(html.escape(label), html.escape(url))}" for label, url in buttons]
            if bib_id:
                lines.append(f'        <button type="button" data-bibtex="{bib_id}">BibTeX</button>')
            lines += [f'        <span class="pub-tag">{inline(t)}</span>' for t in tags]
            lines.append("    </div>")

        if bib_id:
            lines += [f'    <div id="bib_{bib_id}" class="bibtex" hidden>',
                      f"        <pre>{html.escape(bib)}</pre>",
                      "    </div>"]
        lines.append("</article>")
        out += lines + [""]

    return out[:-1]


def render_pub_section(pubs, patents):
    """Heading for the Publications section: plain, or Publications | Patents tabs."""
    if not patents:
        return ["<h2>Publications</h2>"], []
    heading = [
        '<div class="section-tabs" role="tablist" aria-label="Publications and patents">',
        '    <button type="button" role="tab" id="tab-publications" aria-controls="panel-publications" aria-selected="true">Publications</button>',
        '    <button type="button" role="tab" id="tab-patents" aria-controls="panel-patents" aria-selected="false" tabindex="-1">Patents</button>',
        "</div>",
    ]
    panel = (['<div id="panel-patents" role="tabpanel" aria-labelledby="tab-patents">']
             + ["    " + line if line else line for line in patents] + ["</div>"])
    return heading, panel


# --------------------------------------------------------------------------
# gallery.md: photos grouped by event
# --------------------------------------------------------------------------

def slugify(text, used):
    slug = re.sub(r"[^a-z0-9]+", "-", plain(text).lower()).strip("-") or "event"
    base, n = slug, 2
    while slug in used:
        slug, n = f"{base}-{n}", n + 1
    used.add(slug)
    return slug


def parse_gallery(path):
    """Events from gallery.md: [{title, date, place, slug, photos: [(img, caption)]}]."""
    if not path.exists():
        return []
    raw = strip_comments(path.read_text(encoding="utf-8"))
    events, used = [], set()
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("## "):
            parts = [x.strip() for x in line[3:].split("|")] + ["", ""]
            title = parts[0] or "Photos"
            events.append({"title": title, "date": parts[1], "place": parts[2],
                           "slug": slugify(title, used), "photos": []})
        elif line.startswith("- "):
            img, _, caption = (x.strip() for x in line[2:].partition("|"))
            if not img:
                warn(f"{path.name}: skipped empty photo line: {line}")
                continue
            if not (ROOT / img).exists() and not img.startswith("http"):
                warn(f"{path.name}: photo not found: {img}")
            if not events:  # photos before any ## line
                events.append({"title": "Photos", "date": "", "place": "",
                               "slug": slugify("Photos", used), "photos": []})
            events[-1]["photos"].append((img, caption))
        else:
            warn(f"{path.name}: skipped line (expected '## Event | Mon YYYY | Place' or '- photo.jpg'): {line}")
    return [e for e in events if e["photos"]]


def event_meta(e, with_count=False):
    bits = [e["date"], e["place"]]
    if with_count:
        n = len(e["photos"])
        bits.append(f"{n} photo" + ("" if n == 1 else "s"))
    return " · ".join(html.escape(b) for b in bits if b)


def render_gallery_home(events):
    """Home page: one cover tile per event (the first 3 show), linking to it on the Gallery page."""
    out = []
    for e in events:
        out += [
            '<figure class="gallery-item">',
            f'    <a class="gallery-open gallery-cover" href="gallery/#{e["slug"]}">',
            f'        <img src="{html.escape(e["photos"][0][0])}" alt="{html.escape(plain(e["title"]))}" loading="lazy">',
            "    </a>",
            f'    <figcaption><span class="gallery-date">{event_meta(e, with_count=True)}</span>{inline(e["title"])}</figcaption>',
            "</figure>",
        ]
    return out


def render_gallery_page(events, prefix="../"):
    """Gallery page: filter buttons (All + one per event), then one collage of every photo.
    The page lives in gallery/, so photo paths get a ../ prefix."""
    total = sum(len(e["photos"]) for e in events)
    out = ['<div class="gallery-filters" role="group" aria-label="Show photos from">',
           f'    <button type="button" data-filter="all" aria-pressed="true">All photos <span>{total}</span></button>']
    out += [f'    <button type="button" data-filter="{e["slug"]}" aria-pressed="false">'
            f'{inline(e["title"])} <span>{len(e["photos"])}</span></button>' for e in events]
    out += ["</div>", "", '<div class="gallery-grid is-collage">']
    for e in events:
        meta = event_meta(e)  # date · place
        date_html = f'<span class="gallery-date">{meta}</span>' if meta else ""
        for img, caption in e["photos"]:
            src = html.escape(img if img.startswith("http") else prefix + img)
            alt = html.escape(plain(caption or e["title"]))
            text = inline(e["title"]) + (f'<span class="gallery-caption">{inline(caption)}</span>' if caption else "")
            out += [
                f'    <figure class="gallery-item" data-event="{e["slug"]}">',
                f'        <button type="button" class="gallery-open" data-full="{src}" aria-label="Enlarge photo: {alt}">',
                f'            <img src="{src}" alt="{alt}" loading="lazy">',
                "        </button>",
                f"        <figcaption>{date_html}{text}</figcaption>",
                "    </figure>",
            ]
    out.append("</div>")
    return out


# --------------------------------------------------------------------------
# <head> extras: structured data for search engines, optional visitor counter
# --------------------------------------------------------------------------

def head_extra(about):
    s = about["settings"]
    job_title, _, org = plain(s["role"]).partition(",")
    person = {
        "@context": "https://schema.org",
        "@type": "Person",
        "name": s["name"],
        "url": SITE_URL,
        "image": SITE_URL + s["photo"],
        "jobTitle": job_title.strip(),
        "sameAs": [url for _, url in about["links"] if url.startswith("http")],
    }
    if org.strip():
        person["worksFor"] = {"@type": "Organization", "name": org.strip()}
    skills = [i for _, items in about["skills"] for i in items]
    if skills:
        person["knowsAbout"] = skills
    data = json.dumps(person, indent=2, ensure_ascii=False).replace("</", "<\\/")
    lines = ['<script type="application/ld+json">'] + data.splitlines() + ["</script>"]

    code = s.get("analytics", "").strip()
    if code:
        if re.fullmatch(r"[a-z0-9-]+", code):
            lines.append(f'<script data-goatcounter="https://{code}.goatcounter.com/count" '
                         'async src="https://gc.zgo.at/count.js"></script>')
        else:
            warn(f"about.md: analytics should be just your GoatCounter code, e.g. shruti-bt (got {code!r})")
    return lines


def read_template(name):
    text = (TEMPLATES / name).read_text(encoding="utf-8")
    return re.sub(r"\n<!--\s*\n.*?-->\n", "\n", text, count=1, flags=re.S)  # drop the note at the top


# --------------------------------------------------------------------------

def main():
    about = parse_about(CONTENT / "about.md")
    s = about["settings"]
    news = parse_news(CONTENT / "news.md")
    pubs = parse_publications(CONTENT / "publications.md")
    patents = parse_publications(CONTENT / "patents.md")
    pub_heading, patents_panel = render_pub_section(pubs, patents)
    skills = render_skills(about["skills"], s.get("service", "").strip())
    events = parse_gallery(CONTENT / "gallery.md")
    photo_count = sum(len(e["photos"]) for e in events)

    values = {
        "name": html.escape(s["name"]),
        "name_nobreak": html.escape(s["name"]).replace("-", "&#8209;"),  # surname never splits
        "role": inline(s["role"]),
        "photo": html.escape(s["photo"]),
        "focus": indent(render_focus(s.get("focus", "")), 20),
        "highlights": indent(render_highlights(about["highlights"]), 20),
        "about": indent(about["bio"], 16),
        "links": indent(render_links(about["links"]), 16),
        "news": indent(news, 20),
        "pub_heading": indent(pub_heading, 12),
        "publications": indent(pubs, 16),
        "patents_panel": indent(patents_panel, 12),
        "gallery": indent(render_gallery_home(events), 16),
        "gallery_more": (f'            <a href="gallery/" class="gallery-more">See all {photo_count} photos &rarr;</a>'
                         if photo_count else ""),
        "meta": indent(skills, 12),
        "head_extra": indent(head_extra(about), 4),
        "year": str(datetime.date.today().year),
    }

    # Home page
    page = read_template("home.html")
    if not events:  # no photos: no Gallery section, menu link or photo viewer
        page = drop(page, r"\n\s*<section id=\"gallery\">.*?</section>")
        page = drop(page, r"\n\s*<dialog class=\"lightbox\".*?</dialog>")
        page = drop(page, r"\n\s*<a href=\"#gallery\"[^\n]*")
    if not skills:
        page = drop(page, r"\n\s*<section id=\"skills\">.*?</section>")
    (ROOT / "index.html").write_text(BANNER.format(src="content/*.md") + fill(page, values), encoding="utf-8")

    # Gallery page: gallery/index.html, only when there are photos
    gallery_page = ROOT / "gallery" / "index.html"
    if events:
        gvalues = dict(values, gallery=indent(render_gallery_page(events), 8),
                       og_image=events[0]["photos"][0][0])
        gallery_page.parent.mkdir(exist_ok=True)
        gallery_page.write_text(BANNER.format(src="content/gallery.md") + fill(read_template("gallery.html"), gvalues),
                                encoding="utf-8")
    elif gallery_page.exists():
        gallery_page.unlink()

    for w in warnings:
        print("Warning:", w)
    print(f"Built index.html: {len(news) // 4} news items, {pubs.count('</article>')} publications, "
          f"{patents.count('</article>')} patents"
          + (f"; gallery/index.html: {photo_count} photos in {len(events)} events." if events else "; no gallery."))


if __name__ == "__main__":
    main()
